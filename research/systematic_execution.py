# Microstructure Backtest Simulator
# ---------------------------------------------------------------------------

def run_microstructure_backtest(
    prices: Sequence[float] | np.ndarray,
    *,
    timestamps: Sequence[str] | None = None,
    symbol: str = "SPY",
    volumes: Sequence[float] | np.ndarray | None = None,
    highs: Sequence[float] | np.ndarray | None = None,
    lows: Sequence[float] | np.ndarray | None = None,
    gamma_flip_series: Sequence[float] | np.ndarray | None = None,
    call_wall_series: Sequence[float] | np.ndarray | None = None,
    put_wall_series: Sequence[float] | np.ndarray | None = None,
    net_gex_series: Sequence[float] | np.ndarray | None = None,
    net_chex_series: Sequence[float] | np.ndarray | None = None,
    iv_series: Sequence[float] | np.ndarray | None = None,
    initial_capital: float = 100_000.0,
    risk_per_trade_pct: float = 0.02,   # 2% cash risk per trade
    max_position_pct: float = 0.15,     # Max 15% position notional cap (MAX_SINGLE_NAME_PCT)
    slippage_bps: float = 2.0,          # 2 bps half-spread slippage
    commission_per_share: float = 0.005,# $0.005 per share
    max_holding_bars: int = 30,
    enable_delta_hedging: bool = False,
) -> BacktestTearsheet:
    """Run full sequential event-driven backtest over historical microstructure signals.

    Args:
        prices: Underlying bar prices.
        timestamps: Bar timestamps.
        symbol: Ticker symbol.
        volumes: Bar volumes.
        gamma_flip_series: Zero gamma flip price per bar.
        call_wall_series: Call wall price per bar.
        put_wall_series: Put wall price per bar.
        net_gex_series: Net GEX ($M) per bar.
        net_chex_series: Net CHEX ($M) per bar.
        iv_series: Implied volatility per bar.
        initial_capital: Starting portfolio equity ($).
        risk_per_trade_pct: Risk budget per trade.
        slippage_bps: Execution slippage in basis points.
        commission_per_share: Fixed commission per share.
        max_holding_bars: Maximum time horizon before forced exit.
        enable_delta_hedging: If True, computes delta-hedging rebalancing cost.

    Returns:
        BacktestTearsheet containing trade log, equity curve, drawdown, and statistical metrics.
    """
    signals, nw_res, kalman_res, vwap_results = generate_microstructure_signals(
        prices,
        timestamps=timestamps,
        symbol=symbol,
        volumes=volumes,
        highs=highs,
        lows=lows,
        gamma_flip_series=gamma_flip_series,
        call_wall_series=call_wall_series,
        put_wall_series=put_wall_series,
        net_gex_series=net_gex_series,
        net_chex_series=net_chex_series,
        iv_series=iv_series,
    )

    n = len(prices)
    if n == 0:
        return BacktestTearsheet(
            symbol=symbol, n_bars=0, start_date="", end_date="", initial_capital=initial_capital,
            ending_capital=initial_capital, total_net_pnl=0.0, total_return_pct=0.0, cagr_pct=0.0,
            sharpe_ratio=0.0, sortino_ratio=0.0, calmar_ratio=0.0, max_drawdown_pct=0.0,
            max_drawdown_dollar=0.0, win_rate=0.0, profit_factor=0.0, expectancy_per_trade=0.0,
            total_trades=0, winning_trades=0, losing_trades=0, avg_win_dollar=0.0, avg_loss_dollar=0.0,
            win_loss_ratio=0.0, avg_holding_bars=0.0, total_slippage=0.0, total_commissions=0.0,
            total_gamma_pnl=0.0, total_hedging_pnl=0.0, daily_turnover_pct=0.0,
            equity_curve=[], drawdown_curve=[], trades=[], regime_breakdown={},
        )

    ts_list = list(timestamps) if timestamps is not None and len(timestamps) == n else [f"Bar_{i}" for i in range(n)]
    capital = initial_capital
    peak_capital = initial_capital
    trades: list[SimulatedTrade] = []
    trade_id_counter = 1

    active_trade: dict[str, Any] | None = None
    equity_curve: list[dict[str, Any]] = []
    drawdown_curve: list[dict[str, Any]] = []

    total_slippage = 0.0
    total_commissions = 0.0
    total_gamma_pnl = 0.0
    total_hedge_pnl = 0.0
    traded_notional = 0.0

    for t in range(n):
        s_t = float(prices[t])
        sig = signals[t]
        ts = ts_list[t]

        # 1. Manage Active Position (Exits & Trailing Stops)
        if active_trade is not None:
            dir_mult = 1.0 if active_trade["direction"] == "long" else -1.0
            holding_len = t - active_trade["entry_bar"]
            cur_unrealized_pnl = (s_t - active_trade["entry_price"]) * active_trade["shares"] * dir_mult
            risk_r = active_trade["risk_r"]

            # Dynamic Trailing Stop Ratcheting
            if active_trade["direction"] == "long":
                gain_r = (s_t - active_trade["entry_price"]) / risk_r
                if gain_r >= 1.0:
                    active_trade["stop_loss"] = max(active_trade["stop_loss"], active_trade["entry_price"] + 0.35 * risk_r)
                if gain_r >= 2.0:
                    active_trade["stop_loss"] = max(active_trade["stop_loss"], active_trade["entry_price"] + 1.25 * risk_r)
            else:
                gain_r = (active_trade["entry_price"] - s_t) / risk_r
                if gain_r >= 1.0:
                    active_trade["stop_loss"] = min(active_trade["stop_loss"], active_trade["entry_price"] - 0.35 * risk_r)
                if gain_r >= 2.0:
                    active_trade["stop_loss"] = min(active_trade["stop_loss"], active_trade["entry_price"] - 1.25 * risk_r)

            exit_reason = None
            # Take Profit hit
            if active_trade["direction"] == "long" and s_t >= active_trade["take_profit"]:
                exit_reason = "take_profit"
            elif active_trade["direction"] == "short" and s_t <= active_trade["take_profit"]:
                exit_reason = "take_profit"
            # Stop Loss hit (or trailing stop hit)
            elif active_trade["direction"] == "long" and s_t <= active_trade["stop_loss"]:
                exit_reason = "trailing_stop" if active_trade["stop_loss"] > active_trade["entry_price"] else "stop_loss"
            elif active_trade["direction"] == "short" and s_t >= active_trade["stop_loss"]:
                exit_reason = "trailing_stop" if active_trade["stop_loss"] < active_trade["entry_price"] else "stop_loss"
            # Invalidation: Spot crossed gamma flip against direction
            elif (
                active_trade["regime"] == "positive_gamma"
                and active_trade["direction"] == "long"
                and sig.gamma_flip is not None
                and s_t < sig.gamma_flip
                and sig.kalman_zscore < -1.4
            ):
                exit_reason = "invalidation"
            # Time exit with profit locking after 15 bars
            elif holding_len >= 15 and ((active_trade["direction"] == "long" and s_t >= active_trade["entry_price"]) or (active_trade["direction"] == "short" and s_t <= active_trade["entry_price"])):
                exit_reason = "time_profit"
            # Max holding horizon
            elif holding_len >= max_holding_bars:
                exit_reason = "time_horizon"
            # End of series forced close
            elif t == n - 1:
                exit_reason = "session_close"

            if exit_reason is not None:
                # Execute exit fill with slippage
                exit_slip = s_t * (slippage_bps / 10_000.0)
                fill_exit = s_t - exit_slip if active_trade["direction"] == "long" else s_t + exit_slip
                exit_comm = active_trade["shares"] * commission_per_share

                gross_pnl = (fill_exit - active_trade["entry_price"]) * active_trade["shares"] * dir_mult
                trade_slip_cost = (exit_slip + active_trade["entry_slip"]) * active_trade["shares"]
                trade_comm_cost = exit_comm + active_trade["entry_comm"]
                net_pnl = gross_pnl - exit_comm

                # Gamma PnL attribution
                gamma_attr = gross_pnl * (0.35 if active_trade["regime"] == "negative_gamma" else 0.15)
                hedge_cost = (abs(gross_pnl) * 0.05) if enable_delta_hedging else 0.0

                capital += net_pnl
                total_slippage += trade_slip_cost
                total_commissions += trade_comm_cost
                total_gamma_pnl += gamma_attr
                total_hedge_pnl -= hedge_cost
                traded_notional += (fill_exit * active_trade["shares"])

                completed_trade = SimulatedTrade(
                    trade_id=active_trade["trade_id"],
                    symbol=symbol,
                    direction=active_trade["direction"],
                    regime=active_trade["regime"],
                    setup_name=active_trade["setup_name"],
                    entry_bar=active_trade["entry_bar"],
                    entry_time=active_trade["entry_time"],
                    entry_price=round(active_trade["entry_price"], 2),
                    exit_bar=t,
                    exit_time=ts,
                    exit_price=round(fill_exit, 2),
                    exit_reason=exit_reason,
                    shares=round(active_trade["shares"], 2),
                    gross_pnl=round(gross_pnl, 2),
                    net_pnl=round(net_pnl, 2),
                    return_pct=round((net_pnl / max(1.0, active_trade["entry_price"] * active_trade["shares"])) * 100.0, 2),
                    holding_bars=holding_len,
                    slippage_cost=round(trade_slip_cost, 2),
                    transaction_cost=round(trade_comm_cost, 2),
                    gamma_pnl_attribution=round(gamma_attr, 2),
                    delta_hedge_cost=round(hedge_cost, 2),
                )
                trades.append(completed_trade)
                active_trade = None

        # 2. Check for New Entry Signal
        if active_trade is None and sig.action in {"ENTER_LONG", "ENTER_SHORT"} and t < n - 1:
            risk_dollars = capital * risk_per_trade_pct
            price_dist_to_stop = max(0.5, abs(s_t - sig.stop_loss))
            shares = max(1.0, risk_dollars / price_dist_to_stop)
            # Cap position notional at max_position_pct of capital
            max_shares = (capital * max_position_pct) / s_t
            shares = min(shares, max_shares)

            entry_slip = s_t * (slippage_bps / 10_000.0)
            fill_entry = s_t + entry_slip if sig.direction == "long" else s_t - entry_slip
            entry_comm = shares * commission_per_share

            traded_notional += (fill_entry * shares)

            active_trade = {
                "trade_id": trade_id_counter,
                "direction": sig.direction,
                "regime": sig.regime,
                "setup_name": sig.setup_name,
                "entry_bar": t,
                "entry_time": ts,
                "entry_price": fill_entry,
                "entry_slip": entry_slip,
                "entry_comm": entry_comm,
                "stop_loss": sig.stop_loss,
                "take_profit": sig.take_profit,
                "shares": shares,
                "risk_r": price_dist_to_stop,
            }
            trade_id_counter += 1

        # Track Equity & Drawdown
        peak_capital = max(peak_capital, capital)
        dd_dollar = peak_capital - capital
        dd_pct = (dd_dollar / peak_capital) * 100.0 if peak_capital > 0 else 0.0

        equity_curve.append({
            "bar": t,
            "timestamp": ts,
            "equity": round(capital, 2),
            "spot": s_t,
        })
        drawdown_curve.append({
            "bar": t,
            "timestamp": ts,
            "drawdown_pct": round(dd_pct, 3),
            "drawdown_dollar": round(dd_dollar, 2),
        })

    # 3. Calculate Summary Statistics
    total_net_pnl = capital - initial_capital
    total_return_pct = (total_net_pnl / initial_capital) * 100.0
    n_trades = len(trades)
    winning_trades = [tr for tr in trades if tr.net_pnl > 0]
    losing_trades = [tr for tr in trades if tr.net_pnl <= 0]
    n_wins = len(winning_trades)
    n_losses = len(losing_trades)
    win_rate = (n_wins / n_trades * 100.0) if n_trades > 0 else 0.0

    gross_wins = sum(tr.net_pnl for tr in winning_trades)
    gross_losses = abs(sum(tr.net_pnl for tr in losing_trades))
    profit_factor = (gross_wins / gross_losses) if gross_losses > 0 else (99.0 if gross_wins > 0 else 0.0)

    avg_win = (gross_wins / n_wins) if n_wins > 0 else 0.0
    avg_loss = (gross_losses / n_losses) if n_losses > 0 else 0.0
    win_loss_ratio = (avg_win / avg_loss) if avg_loss > 0 else 0.0
    expectancy = (total_net_pnl / n_trades) if n_trades > 0 else 0.0
    avg_holding = (sum(tr.holding_bars for tr in trades) / n_trades) if n_trades > 0 else 0.0

    # Max Drawdown
    max_dd_pct = max((d["drawdown_pct"] for d in drawdown_curve), default=0.0)
    max_dd_dollar = max((d["drawdown_dollar"] for d in drawdown_curve), default=0.0)

    # Returns & Sharpe calculation
    eq_series = pd.Series([d["equity"] for d in equity_curve])
    pct_returns = eq_series.pct_change().dropna()
    mean_ret = pct_returns.mean()
    std_ret = pct_returns.std(ddof=1)
    # Annualized with 252 factor
    sharpe = float((mean_ret / std_ret * math.sqrt(252.0))) if std_ret > 1e-8 else 0.0

    # Sortino (downside deviation)
    downside_returns = pct_returns[pct_returns < 0]
    downside_std = downside_returns.std(ddof=1)
    sortino = float((mean_ret / downside_std * math.sqrt(252.0))) if downside_std > 1e-8 else 0.0

    # Calmar Ratio
    calmar = (total_return_pct / max_dd_pct) if max_dd_pct > 0 else 0.0
    cagr = ((capital / initial_capital) ** (252.0 / max(1, n)) - 1.0) * 100.0

    # Daily Turnover
    daily_turnover_pct = (traded_notional / (initial_capital * max(1, n / 252.0))) * 100.0

    # 4. Regime-Segmented Tearsheet
    regimes = ["positive_gamma", "negative_gamma", "neutral_transition"]
    regime_breakdown: dict[str, RegimeMetrics] = {}
    for reg in regimes:
        reg_trades = [tr for tr in trades if tr.regime == reg]
        reg_n = len(reg_trades)
        if reg_n > 0:
            reg_wins = len([tr for tr in reg_trades if tr.net_pnl > 0])
            reg_win_rate = (reg_wins / reg_n) * 100.0
            reg_pnl = sum(tr.net_pnl for tr in reg_trades)
            reg_gross_w = sum(tr.net_pnl for tr in reg_trades if tr.net_pnl > 0)
            reg_gross_l = abs(sum(tr.net_pnl for tr in reg_trades if tr.net_pnl <= 0))
            reg_pf = (reg_gross_w / reg_gross_l) if reg_gross_l > 0 else 99.0
            reg_avg_ret = sum(tr.return_pct for tr in reg_trades) / reg_n
            reg_metrics = RegimeMetrics(
                regime_name=reg,
                n_trades=reg_n,
                win_rate=round(reg_win_rate, 2),
                profit_factor=round(reg_pf, 2),
                total_net_pnl=round(reg_pnl, 2),
                avg_return_pct=round(reg_avg_ret, 2),
                sharpe_ratio=round(reg_avg_ret / (abs(reg_avg_ret) + 1.0), 2),
            )
        else:
            reg_metrics = RegimeMetrics(
                regime_name=reg,
                n_trades=0,
                win_rate=0.0,
                profit_factor=0.0,
                total_net_pnl=0.0,
                avg_return_pct=0.0,
                sharpe_ratio=0.0,
            )
        regime_breakdown[reg] = reg_metrics

    return BacktestTearsheet(
        symbol=symbol,
        n_bars=n,
        start_date=ts_list[0],
        end_date=ts_list[-1],
        initial_capital=round(initial_capital, 2),
        ending_capital=round(capital, 2),
        total_net_pnl=round(total_net_pnl, 2),
        total_return_pct=round(total_return_pct, 2),
        cagr_pct=round(cagr, 2),
        sharpe_ratio=round(sharpe, 2),
        sortino_ratio=round(sortino, 2),
        calmar_ratio=round(calmar, 2),
        max_drawdown_pct=round(max_dd_pct, 2),
        max_drawdown_dollar=round(max_dd_dollar, 2),
        win_rate=round(win_rate, 2),
        profit_factor=round(profit_factor, 2),
        expectancy_per_trade=round(expectancy, 2),
        total_trades=n_trades,
        winning_trades=n_wins,
        losing_trades=n_losses,
        avg_win_dollar=round(avg_win, 2),
        avg_loss_dollar=round(avg_loss, 2),
        win_loss_ratio=round(win_loss_ratio, 2),
        avg_holding_bars=round(avg_holding, 1),
        total_slippage=round(total_slippage, 2),
        total_commissions=round(total_commissions, 2),
        total_gamma_pnl=round(total_gamma_pnl, 2),
        total_hedging_pnl=round(total_hedge_pnl, 2),
        daily_turnover_pct=round(daily_turnover_pct, 2),
        equity_curve=equity_curve,
        drawdown_curve=drawdown_curve,
        trades=trades,
        regime_breakdown=regime_breakdown,
    )
