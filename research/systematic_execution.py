def generate_microstructure_signals(
    prices: Sequence[float] | np.ndarray,
    *,
    timestamps: Sequence[str] | None = None,
    symbol: str = "SPY",
    volumes: Sequence[float] | np.ndarray | None = None,
    highs: Sequence[float] | np.ndarray | None = None,
    lows: Sequence[float] | np.ndarray | None = None,
    gamma_flip_series: Sequence[float] | np.ndarray | None = None,
    call_wall_series: Sequence[float] | np.ndarray | None = None,
    put_wall_series: Sequence[float] | np.ndarray | None = None,
    net_gex_series: Sequence[float] | np.ndarray | None = None,
    net_chex_series: Sequence[float] | np.ndarray | None = None,
    iv_series: Sequence[float] | np.ndarray | None = None,
    base_bandwidth: float = 20.0,
    envelope_alpha: float = 2.0,
    kalman_sigma_q: float = 1e-3,
    kalman_sigma_r: float = 1.0,
    breakout_z: float = 1.6,
    exhaustion_z: float = 0.4,
    enable_0dte_charm_override: bool = True,
) -> tuple[list[ExecutionSignal], NadarayaWatsonEnvelopeResult, KinematicKalmanResult, list[AnchoredVWAPResult]]:
    """Evaluate full microstructure decision hierarchy across bars to produce actionable execution signals.

    Decision Rules:
      1. Positive Gamma Regime (S_t > S* and GEX_net > 0):
         - Long: S_t <= Lower Envelope, S_t > Put Wall, Kalman z-score >= -exhaustion_z (exhaustion of downside momentum)
         - Short: S_t >= Upper Envelope, S_t <= Call Wall * 1.002, Kalman z-score <= +exhaustion_z (upside deceleration)
         - Invalidation: S_t crosses below S* on accelerating velocity (z_v < -1.5)
         - 0DTE Charm: If enabled and post-14:00 with CHEX > 0, suppress short signals and extend long targets

      2. Negative Gamma Regime (S_t < S* and GEX_net < 0):
         - Short Breakdown: S_t breaches Put Wall, S_t < VWAP, lower envelope expands down, z_v < -breakout_z
         - Long Short-Squeeze: S_t breaks above Call Wall, upper envelope expands up, z_v > +breakout_z
         - Invalidation: False breakout re-crossing S*

    Returns:
        Tuple of (signals_list, nw_result, kalman_result, vwap_results)
    """
    p = np.asarray(prices, dtype=float)
    n = len(p)
    if n == 0:
        empty_nw = NadarayaWatsonEnvelopeResult(np.array([]), np.array([]), np.array([]), np.array([]), np.array([]), np.array([]))
        empty_k = KinematicKalmanResult(np.array([]), np.array([]), np.array([]), np.array([]), np.array([]), np.array([]), np.array([]), np.array([]), np.array([]), np.array([], dtype=bool), np.array([], dtype=bool))
        return [], empty_nw, empty_k, []

    v = np.asarray(volumes, dtype=float) if volumes is not None and len(volumes) == n else np.ones(n, dtype=float)
    ts_list = list(timestamps) if timestamps is not None and len(timestamps) == n else [f"Bar_{i}" for i in range(n)]

    # 1. State Estimation Calculations
    nw_res = causal_nadaraya_watson_envelope(
        p,
        base_bandwidth=base_bandwidth,
        alpha=envelope_alpha,
        gex_series=net_gex_series,
        use_dynamic_bandwidth=True,
    )

    kalman_res = kinematic_kalman_filter(
        p,
        dt=1.0,
        base_sigma_q=kalman_sigma_q,
        sigma_r=kalman_sigma_r,
        iv_series=iv_series,
        gex_series=net_gex_series,
        breakout_z=breakout_z,
        exhaustion_z=exhaustion_z,
    )

    # Risk unit: the one-bar 1-sigma move that every stop and target is quoted
    # in. Kept separate from the envelope's sigma_local, which measures channel
    # width over a long lookback and is not a per-bar risk figure.
    risk_units, risk_basis = compute_bar_volatility_unit(
        p, highs=highs, lows=lows, iv_series=iv_series
    )

    # Microstructure Anchored VWAP (anchors at bar 0 and whenever spot crosses gamma flip)
    flip_crossings = [0]
    if gamma_flip_series is not None and len(gamma_flip_series) == n:
        for t in range(1, n):
            prev_s = p[t - 1]
            curr_s = p[t]
            flip = gamma_flip_series[t]
            if (prev_s < flip <= curr_s) or (prev_s > flip >= curr_s):
                flip_crossings.append(t)
    # Keep bar 0 (the window anchor) plus the four MOST RECENT flip crossings,
    # not the oldest. `sorted(set(...))[:5]` kept the five oldest crossings
    # and silently dropped every recent one -- on any window with more than
    # five crossings the anchors shown were stale by construction, discarding
    # exactly the regime changes closest to the current bar that a trader
    # would care about.
    flip_crossings = sorted(set(flip_crossings))
    recent_crossings = [c for c in flip_crossings if c != 0][-4:]
    flip_crossings = sorted({0, *recent_crossings})
    anchor_names = [
        "Session_Open" if c == 0 else f"Flip_Cross_Bar_{c}" for c in flip_crossings
    ]

    vwap_results = compute_anchored_vwap(p, v, flip_crossings, anchor_names)
    primary_vwap = vwap_results[0].vwap if vwap_results else p

    # 2. Sequential Signal Generation
    signals: list[ExecutionSignal] = []

    for t in range(n):
        s_t = p[t]
        s_prev = p[t - 1] if t > 0 else s_t
        ts = ts_list[t]

        # Structural levels are used only when they were actually supplied.
        # Falling back to fixed percentages of the current close manufactured a
        # "gamma flip" that was, by construction, always 1.5% below spot -- so
        # every bar read as positive gamma and the regime branch below was
        # decided by arithmetic on the price rather than by dealer positioning.
        has_gamma = (
            gamma_flip_series is not None and len(gamma_flip_series) == n
            and net_gex_series is not None and len(net_gex_series) == n
        )
        flip = float(gamma_flip_series[t]) if has_gamma else None
        c_wall = float(call_wall_series[t]) if call_wall_series is not None and len(call_wall_series) == n else None
        p_wall = float(put_wall_series[t]) if put_wall_series is not None and len(put_wall_series) == n else None
        net_gex = float(net_gex_series[t]) if has_gamma else None
        net_chex = net_chex_series[t] if net_chex_series is not None and len(net_chex_series) == n else 0.0

        upper_band = nw_res.upper[t]
        lower_band = nw_res.lower[t]
        k_mean = nw_res.mean[t]
        prev_low_band = nw_res.lower[t - 1] if t > 0 else lower_band
        prev_up_band = nw_res.upper[t - 1] if t > 0 else upper_band
        vwap_t = primary_vwap[t] if not np.isnan(primary_vwap[t]) else s_t
        v_k = kalman_res.velocity[t]
        v_z = kalman_res.velocity_zscore[t]
        v_prev_z = kalman_res.velocity_zscore[t - 1] if t > 0 else v_z
        sigma_loc = max(0.5, nw_res.sigma_local[t])
        # Stops and targets are quoted in `u`, never in sigma_loc.
        u = float(max(1e-6, risk_units[t]))

        # Trend estimation from causal kernel mean
        lag_k = max(0, t - 5)
        trend_up = k_mean >= nw_res.mean[lag_k]

        # Topography Quadrant.
        #
        # With no gamma data the engine does not guess at a gamma regime. It
        # falls back to the price-structure analogue of the same question --
        # is the tape extending or reverting -- read off the Kalman velocity
        # z-score, and labels it "gamma_unmeasured" so nothing downstream
        # reports a dealer-positioning claim that was never measured.
        if not has_gamma:
            regime = "gamma_unmeasured"
        else:
            is_pos_gex = (s_t >= flip) and (net_gex >= 0)
            regime = "positive_gamma" if is_pos_gex else "negative_gamma"
            if abs(s_t - flip) <= 0.0025 * s_t:
                regime = "neutral_transition"

        action = "NONE"
        direction = "flat"
        setup_name = "None"
        conviction = 0.0
        stop_loss = 0.0
        take_profit = 0.0
        tp_1r = 0.0
        tp_2r = 0.0
        tp_3r = 0.0
        # "kernel" -> target the causal mean, clamped into the 1R-3R band.
        # "r2"     -> target 2R. Set by whichever branch fires.
        target_mode = "r2"
        charm_extend = False
        invalidation = ""
        notes = []

        # 0DTE Charm unhedging check: Afternoon session (e.g. index > 70% of day or timestamp has '14:'/'15:')
        is_afternoon = ("14:" in ts or "15:" in ts or (n >= 20 and t >= int(n * 0.7)))
        charm_melt_up_active = (
            enable_0dte_charm_override
            and is_afternoon
            and (net_chex > 0 or (net_gex is not None and net_gex > 0))
        )

        # Decision Tree.
        #
        # `mode` is what actually selects the branch: "revert" runs the
        # band-fade setups, "extend" the breakout setups. With gamma measured,
        # the regime picks it (long gamma dampens -> revert; short gamma
        # amplifies -> extend). Without gamma, kinematics pick it -- a velocity
        # z-score beyond the breakout threshold is the price-only evidence that
        # the tape is extending. Same setups either way; only the evidence for
        # choosing between them changes, and the ticket says which it was.
        if regime == "positive_gamma":
            mode = "revert"
        elif regime == "negative_gamma":
            mode = "extend"
        elif regime == "gamma_unmeasured":
            mode = "extend" if abs(v_z) > breakout_z else "revert"
        else:
            mode = "none"

        gamma_tag = "PosGEX" if regime == "positive_gamma" else "NegGEX" if regime == "negative_gamma" else "Kinematic"

        if mode == "revert":
            if c_wall is not None and p_wall is not None:
                topography_quadrant = "forward_positive_ramp" if c_wall - s_t <= s_t - p_wall else "backward_positive_ramp"
            else:
                topography_quadrant = "kinematic_range"

            # Long Setup: Touch/penetrate lower band with momentum stabilizing
            if (s_t <= lower_band or s_prev <= prev_low_band) and (v_z >= -0.6 or v_z > v_prev_z):
                action = "ENTER_LONG"
                direction = "long"
                setup_name = f"{gamma_tag}_LowerBand_Exhaustion"
                conviction = min(0.95, 0.72 + max(0.0, lower_band - s_t) / max(1e-4, sigma_loc))
                # Stop one bar-sigma beyond whichever is lower, spot or the band
                # being reverted from. The mean-reversion target is the kernel
                # mean, held inside the 1R-3R ladder so it stays a move the bar
                # volatility can actually produce.
                stop_loss = min(s_t, lower_band) - 1.0 * u
                target_mode = "kernel"
                invalidation = (
                    f"Spot closing below Gamma Flip ${flip:.2f} with negative acceleration"
                    if flip is not None
                    else "Spot closing below the lower envelope with negative acceleration"
                )
                notes.append(
                    "Positive GEX mean-reversion long; dealer put hedging creates supportive floor"
                    if regime == "positive_gamma"
                    else "Kinematic mean-reversion long at the lower envelope; no dealer-gamma read available"
                )
                if charm_melt_up_active:
                    charm_extend = True
                    notes.append("0DTE Charm melt-up active; extended take-profit target above standard VWAP")

            # Short Setup: Touch/penetrate upper band with upside stalling (and not strong bull trend)
            elif (s_t >= upper_band or s_prev >= prev_up_band) and (v_z <= 0.6 or v_z < v_prev_z) and not trend_up:
                if charm_melt_up_active:
                    notes.append("Short signal suppressed due to 0DTE afternoon Charm unhedging melt-up flow")
                else:
                    action = "ENTER_SHORT"
                    direction = "short"
                    setup_name = f"{gamma_tag}_UpperBand_Deceleration"
                    conviction = min(0.95, 0.72 + max(0.0, s_t - upper_band) / max(1e-4, sigma_loc))
                    stop_loss = max(s_t, upper_band) + 1.0 * u
                    target_mode = "kernel"
                    invalidation = (
                        f"Spot breaking above Call Wall ${c_wall:.2f} on accelerating volume"
                        if c_wall is not None
                        else "Spot breaking above the upper envelope on accelerating volume"
                    )
                    notes.append(
                        "Positive GEX mean-reversion short; dealer call hedging creates overhead resistance"
                        if regime == "positive_gamma"
                        else "Kinematic mean-reversion short at the upper envelope; no dealer-gamma read available"
                    )

        elif mode == "extend":
            if c_wall is not None and p_wall is not None:
                topography_quadrant = "forward_negative_slide" if s_t - p_wall <= c_wall - s_t else "backward_negative_slide"
            else:
                topography_quadrant = "kinematic_expansion"

            # Short Breakdown: Breach below lower band (or the put wall, when
            # one is measured) with strong negative kinematic acceleration.
            breached_down = s_t < lower_band or (p_wall is not None and s_t <= p_wall)
            breached_up = s_t > upper_band or (c_wall is not None and s_t >= c_wall)

            # Trend & Freshness Filters:
            # 1. Macro indices (SPY, QQQ, etc.) have strong structural upward drift and dealer put-support.
            #    Short breakdown cascades without confirmed negative gamma are prone to bear traps.
            # 2. Short breakdowns require alignment with trend (not trend_up) to avoid shorting dips in bull trends.
            # 3. Freshness: only trigger if breach occurred within the last 2 bars (not chasing exhausted moves).
            is_macro_index = symbol.upper() in {"SPY", "QQQ", "IWM", "DIA"}
            fresh_upper = (s_prev <= prev_up_band) or (t >= 2 and p[t - 2] <= nw_res.upper[t - 2])
            fresh_lower = (s_prev >= prev_low_band) or (t >= 2 and p[t - 2] >= nw_res.lower[t - 2])

            allow_short_cascade = (
                not (is_macro_index and regime == "gamma_unmeasured")
                and (not trend_up or regime == "negative_gamma")
                and (fresh_lower or p_wall is not None)
            )
            allow_long_expansion = (
                (trend_up or regime == "negative_gamma")
                and (fresh_upper or c_wall is not None)
            )

            if breached_down and v_z < -breakout_z and allow_short_cascade:
                action = "ENTER_SHORT"
                direction = "short"
                setup_name = f"{gamma_tag}_PutWall_Cascade" if p_wall is not None else f"{gamma_tag}_LowerBreak_Cascade"
                conviction = min(0.98, 0.75 + (abs(v_z) - breakout_z) * 0.1)
                # Breakdown: the risk is a reclaim of the level that broke,
                # capped at one bar-sigma so the stop stays a volatility
                # distance rather than a channel width. Target is 2R.
                stop_loss = min(s_t + 1.0 * u, max(s_t, lower_band) + 0.5 * u)
                target_mode = "r2"
                invalidation = (
                    f"False breakdown: Spot re-crossing above Gamma Flip ${flip:.2f}"
                    if flip is not None
                    else "False breakdown: Spot re-crossing above the kernel mean"
                )
                notes.append(
                    "Negative GEX breakdown cascade; dealer short-delta hedging accelerates selling"
                    if regime == "negative_gamma"
                    else "Kinematic breakdown on velocity expansion; no dealer-gamma read available"
                )

            # Long Short-Squeeze: Decisive breakout above the upper band (or the
            # call wall, when measured) with positive velocity.
            elif breached_up and v_z > breakout_z and allow_long_expansion:
                action = "ENTER_LONG"
                direction = "long"
                setup_name = f"{gamma_tag}_CallWall_ShortSqueeze" if c_wall is not None else f"{gamma_tag}_UpperBreak_Expansion"
                conviction = min(0.98, 0.75 + (v_z - breakout_z) * 0.1)
                stop_loss = max(s_t - 1.0 * u, min(s_t, upper_band) - 0.5 * u)
                target_mode = "r2"
                invalidation = (
                    f"False breakout: Spot re-crossing below Call Wall ${c_wall:.2f}"
                    if c_wall is not None
                    else "False breakout: Spot re-crossing below the kernel mean"
                )
                notes.append(
                    "Negative GEX short-squeeze; dealer short-covering and positive vanna kick accelerate rally"
                    if regime == "negative_gamma"
                    else "Kinematic breakout on velocity expansion; no dealer-gamma read available"
                )
        else:
            topography_quadrant = "transition_zone"

        # One R is the distance to the stop actually quoted on this ticket --
        # the standard definition -- so "2R" on the ladder is genuinely twice
        # what the trade loses if it is wrong, and risk_reward below is exact
        # rather than an approximation of a sigma multiple.
        stop_dist = abs(s_t - stop_loss) if action in {"ENTER_LONG", "ENTER_SHORT"} else 0.0
        if stop_dist > 1e-9:
            sign = 1.0 if direction == "long" else -1.0
            tp_1r = s_t + sign * stop_dist
            tp_2r = s_t + sign * 2.0 * stop_dist
            tp_3r = s_t + sign * 3.0 * stop_dist
            if target_mode == "kernel":
                # Revert to the causal mean, but never book a target the bar
                # volatility cannot reach, nor one inside 1R.
                take_profit = (
                    min(max(k_mean, tp_1r), tp_3r) if direction == "long"
                    else max(min(k_mean, tp_1r), tp_3r)
                )
            else:
                take_profit = tp_2r
            if charm_extend:
                take_profit = (
                    min(take_profit + 0.5 * u, tp_3r) if direction == "long"
                    else max(take_profit - 0.5 * u, tp_3r)
                )

        # Position size is solved from the stop, not scaled off conviction.
        # `conviction * 10` put 8.4% of capital behind an 84%-conviction ticket
        # no matter how far the stop was, so an unusually wide stop silently
        # multiplied the loss it was sized against. Conviction now sets the risk
        # budget (0.25%-1.00% of capital) and the stop distance decides how much
        # notional that budget buys.
        if stop_dist > 1e-9 and s_t > 0:
            risk_budget_pct = 0.25 + 0.75 * conviction
            # MAX_SINGLE_NAME_PCT caps concentration: a very tight stop would
            # otherwise solve to a position larger than the book should hold in
            # one name, however small the loss at the stop.
            size_pct = min(MAX_SINGLE_NAME_PCT, risk_budget_pct * s_t / stop_dist)
            reward_risk = abs(take_profit - s_t) / stop_dist
        else:
            size_pct = 0.0
            reward_risk = 0.0

        sig = ExecutionSignal(
            bar_index=t,
            timestamp=ts,
            symbol=symbol,
            action=action,
            direction=direction,
            price=round(s_t, 2),
            regime=regime,
            topography_quadrant=topography_quadrant,
            setup_name=setup_name,
            conviction=round(conviction, 3),
            suggested_size_pct=round(size_pct, 1),
            entry_price=round(s_t, 2),
            stop_loss=round(stop_loss, 2),
            take_profit=round(take_profit, 2),
            invalidation_anchor=invalidation,
            kalman_velocity=round(v_k, 4),
            kalman_zscore=round(v_z, 3),
            kernel_mean=round(k_mean, 2),
            upper_envelope=round(upper_band, 2),
            lower_envelope=round(lower_band, 2),
            anchored_vwap=round(vwap_t, 2),
            call_wall=round(c_wall, 2) if c_wall is not None else None,
            put_wall=round(p_wall, 2) if p_wall is not None else None,
            gamma_flip=round(flip, 2) if flip is not None else None,
            risk_unit=round(u, 4),
            risk_unit_basis=risk_basis,
            risk_reward=round(reward_risk, 2),
            target_1r=round(tp_1r, 2),
            target_2r=round(tp_2r, 2),
            target_3r=round(tp_3r, 2),
            notes=notes,
        )
        signals.append(sig)

    return signals, nw_res, kalman_res, vwap_results


